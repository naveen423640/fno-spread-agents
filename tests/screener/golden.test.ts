import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

describe('screener golden fixture (generated by screener/gen_golden.py from the Python reference)', () => {
  const golden = JSON.parse(readFileSync('tests/fixtures/screener/golden.json', 'utf8')) as Record<string, unknown>;

  it('has every section the parity tests rely on', () => {
    for (const key of ['params', 'data', 'indicator_index', 'indicators', 'masks', 'simulate', 'backtest', 'scans', 'expiry', 'fy_opt', 'bs', 'nice_step']) expect(golden, key).toHaveProperty(key);
  });

  it('records the reference parameters unchanged', () => {
    expect(golden.params).toMatchObject({ hv_pct_max: 0.6, hold_days: 20, time_exit_left: 8, take_profit: 0.6, stop_loss: 0.5, slippage: 0.02 });
    expect((golden.params as { rsi_bull: number[] }).rsi_bull).toEqual([35, 48]);
    expect((golden.params as { rsi_bear: number[] }).rsi_bear).toEqual([52, 65]);
  });

  it('covers SIGNAL and WATCH rows on both sides and all six variants', () => {
    const scans = golden.scans as { raw: { status: string; side: string }[] }[];
    const rows = scans.flatMap((scan) => scan.raw);
    expect(new Set(rows.map((row) => row.status))).toEqual(new Set(['SIGNAL', 'WATCH']));
    expect(new Set(rows.map((row) => row.side))).toEqual(new Set(['BULL CALL', 'BEAR PUT']));
    expect(Object.keys(golden.backtest as object)).toHaveLength(6);
  });
});
